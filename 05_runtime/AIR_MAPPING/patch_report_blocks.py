#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""10번 노드에 「조사 결과 점검」 블록을 붙인다 — 어느 변형 위에든 얹을 수 있다.

넣는 것은 셋뿐이고, 셋 다 **세는 일**이다. 모델이 문장을 지어낼 자리가 없다.

  ① 출처 확인 상태    출처 꼬리가 있었나 없었나. 도구가 준 사실이라 못 속인다
  ② 영역별 근거 확보  5개 영역에 근거가 붙었나. 빈 영역이 곧 다음 조사 지시서다
  ③ 스크리닝 대조     점수를 준 축에 근거가 붙었나. 어긋난 칸이 판단거리다

넣지 않은 것 — 당사 순위·점유율을 상단에 다시 싣는 블록.
담당자가 이미 아는 숫자다. 읽고 나서 하는 행동이 바뀌지 않는다.

「확인 n건 · 추정 n건」도 상단에 올리지 않는다. 그 라벨은 모델이 스스로 붙인 값이라,
틀리면 요약도 같이 틀린 채로 더 그럴싸해진다. 상단에는 기계가 셀 수 있는 것만 둔다.
(그 집계는 종전대로 뒤쪽 〈검수용〉 블록에 남는다.)

    python3 patch_report_blocks.py <입력.json> [<출력.json>]
    python3 patch_report_blocks.py --all      # 기준선 · D · D+B 에 일괄 적용
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))

# ── 화면 레이아웃에 □ 한 줄을 끼운다 ──────────────────────
OLD_LAYOUT = """<#번호 주제명>

□ 핵심 판단"""
NEW_LAYOUT = """<#번호 주제명>

□ 조사 결과 점검         <- 본문보다 먼저 낸다. 규칙은 아래 별도 절

□ 핵심 판단"""

ANCHOR = '## 본문에 내부 용어를 쓰지 않는다 — HARD RULE'

SECTION = """## □ 조사 결과 점검 — 세는 블록이다. HARD RULE

이 블록은 보고서 맨 앞에 낸다. 읽는 사람이 **본문을 어디까지 믿을지 먼저 알아야** 하기 때문이다.

**여기 들어가는 값은 전부 세어서 나온다. 문장을 지어 쓰는 칸이 하나도 없다.**
판단을 적지 않는다. 전망을 적지 않는다. 세고, 적고, 끝낸다.

### ○ (출처 확인 상태)

근거 전체를 세고, 출처 파일명이 있는 것과 없는 것으로 나눈다.

    ○ (출처 확인 상태) 근거 <N>건
    - 출처 파일명 확인 <n>건 — <근거 번호 나열>
    - 출처 미상 <n>건 — <근거 번호 나열>
     · 조회는 있었으나 자료원이 파일명을 주지 않은 근거. 본 보고서 사용 전 확인 필요

- 판정 기준은 하나다. `source_paths` 가 비어 있지 않으면 확인, 비어 있으면 미상.
  **검증상태(확인·부분확인·추정)를 보지 않는다.** 그것은 판단이고 이것은 사실이다.
- MRI 원문에 근거한 항목은 양쪽 어디에도 넣지 않고 따로 적는다 — `- MRI 원문 기반 <n>건`
- 출처 미상이 0건이면 그 줄을 뺀다. **0건이 아니면 절대 빼지 않는다.**

### ○ (영역별 근거 확보)

5개 영역에 근거가 붙었는지를 센다. 세 값만 쓴다 — `확보` · `부분` · `미확보`.

    ○ (영역별 근거 확보)
    - 정책·제도 <확보> · 산업·고객 <확보> · 금융업권·경쟁사 <부분> · 자산운용·펀드시장 <확보> · 당사 현황 <미확보>
    - <부분·미확보인 영역마다 한 줄> 무엇까지 확인됐고 무엇이 확인되지 않았는지

- `확보` 는 그 영역에 근거가 붙었고 수치나 사실이 확인된 경우다.
- `부분` 은 존재는 확인했으나 규모·실적 같은 핵심 값이 없는 경우다.
- `미확보` 는 근거가 붙지 않은 경우다. **「해당 없음」과 구분한다.**
  자료원이 연결되지 않아 조사하지 못한 영역은 그 사유를 그대로 적는다.
  · 「당사 현황 — 내부 자료 미연결로 조사 불가」는 「당사는 해당 활동이 없음」이 아니다.
    **이 구분을 흐리면 담당자가 잘못된 전제로 판단한다.**

### ○ (스크리닝 판정과의 대조)

인계 자료에 관점별 점수가 있을 때만 만든다.

    ○ (스크리닝 판정과의 대조)
    - 상품 <점수> → 근거 <번호 나열 또는 없음>
    - 고객 <점수> → 근거 <…>
    - 채널 <점수> → 근거 <…>
    - 그룹협업 <점수> → 근거 <…>
    - 투자테마 <점수> → 근거 <…>
    · <1점 이상인데 근거가 없는 축을 짚는 한 줄>

- 오른쪽 칸에는 **근거 번호만** 쓴다. 설명을 쓰지 않는다.
  근거가 없으면 `없음` 이라고만 쓴다. **말로 메우지 않는다.**
- **1점 이상을 받았는데 근거가 붙지 않은 축이 이 블록의 목적이다.** 반드시 짚는다.
  · 스크리닝이 과대평가했거나, 조사가 그 축을 놓쳤거나 둘 중 하나다.
    어느 쪽인지는 담당자가 정한다. **네가 어느 한쪽으로 단정하지 않는다.**
- 점수가 입력에 없으면 **이 블록을 통째로 생략한다.** 빈 표를 만들지 않는다.
  점수를 기억이나 본문에서 역산해 채우지 않는다.

### 이 블록에 쓰지 않는 것

- 당사 순위·점유율 — 본문 「당사 현황」에 있다. 앞에 다시 싣지 않는다
- 종합 판단·권고 — 「핵심 판단」의 몫이다
- 확인·부분확인·추정 건수 — 뒤쪽 〈검수용〉 블록에 있다
- 「전반적으로 양호」 같은 총평 — 이 블록에 형용사를 쓰지 않는다

`final_report_text` 에도 같은 블록을 같은 자리에 넣는다. 화면에만 내지 않는다.
"""


def patch(src, dst):
    d = json.load(open(src, encoding='utf-8'))
    n = [x for x in d['MapValue']['FunctionMaps']
         if (x.get('COL_NAME') or '').startswith('10 ')][0]
    p = n['prompt']
    old = len(p)
    assert '조사 결과 점검' not in p, '이미 적용된 파일'
    assert OLD_LAYOUT in p, '레이아웃 블록을 찾지 못함'
    p = p.replace(OLD_LAYOUT, NEW_LAYOUT, 1)
    i = p.index(ANCHOR)
    p = p[:i] + SECTION + '\n' + p[i:]
    n['prompt'] = p
    json.dump(d, open(dst, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print(f"{os.path.basename(dst):<30} 10번 프롬프트 {old:,} -> {len(p):,}자")


def main():
    if '--all' in sys.argv:
        for s, t in (('variant_D_raw.json',   'variant_D_report.json'),
                     ('variant_D_on_B.json',  'variant_D_on_B_report.json'),
                     ('MRI_Agent2_Research_Response_v2.json', 'variant_report.json')):
            sp = os.path.join(HERE, s)
            if os.path.exists(sp):
                patch(sp, os.path.join(HERE, t))
        return
    if len(sys.argv) < 2:
        print(__doc__); return
    src = sys.argv[1]
    dst = sys.argv[2] if len(sys.argv) > 2 else src.replace('.json', '_report.json')
    patch(src, dst)


if __name__ == '__main__':
    main()
