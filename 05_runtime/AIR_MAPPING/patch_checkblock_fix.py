#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""⑱ 점검 블록의 구멍 하나 — 「MRI 원문 기반」을 식별하는 방법을 안 적었다.

조회가 된 실행의 두 블록이 서로 다른 말을 했다.

    □ 조사 결과 점검  →  근거 0건 / 파일명 확인 0 / 출처 미상 0 / MRI 원문 기반 13건
    〈검수용〉         →  근거 13건 (확인 13) / 정책 5 · 뉴스 5 · 협회통계 3 · MRI 원문 0

검수용이 맞다. 그 실행은 실제로 조회했고 13건을 확보했다.
점검 블록만 틀렸고, 원인은 내가 쓴 규칙의 구멍 하나다.

기존 규칙은 이렇게만 적혀 있었다.

    - 판정 기준은 하나다. `source_paths` 가 비어 있지 않으면 확인, 비어 있으면 미상.
    - MRI 원문에 근거한 항목은 양쪽 어디에도 넣지 않고 따로 적는다 — `MRI 원문 기반 <n>건`

**「MRI 원문에 근거한 항목」을 무엇으로 알아보는지를 안 적었다.**
근거 카드에 그 칸은 있다 — 07 이 MRI 기반 근거에
`"source_names": ["MRI 원문"], "source_paths": []` 를 넣게 되어 있다.
규칙이 그 칸을 가리키지 않으니 모델이 옆 칸으로 대신했다.
`source_paths` 가 비어 있는 것을 전부 「MRI 원문 기반」으로 읽었다.
그리고 「따로 적는다」를 「총계에서 뺀다」로 읽어 N 이 0이 됐다.

구멍 하나에서 증상 셋이 나왔다.

  1. 헤더 `근거 0건` 인데 하위 합이 13
  2. 정책·뉴스·협회통계에서 조회된 13건이 「MRI 원문 기반」으로 분류
  3. 영역별 전부 `미확보` · 스크리닝 대조 전부 `근거 없음`
     — 13건이 별도 바구니로 빠져 근거 목록이 비어 보였다

그래서 판정을 **세 갈래로 빠짐없이** 만들고, 합계가 맞는지 세게 한다.

    python3 patch_checkblock_fix.py            # 점검 블록이 있는 모든 변형에 제자리 적용
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
TARGETS = ['variant_report_call.json', 'variant_report.json',
           'variant_D_report.json', 'variant_D_on_B_report.json']

OLD_TPL = """    ○ (출처 확인 상태) 근거 <N>건
    - 출처 파일명 확인 <n>건 — <근거 번호 나열>
    - 출처 미상 <n>건 — <근거 번호 나열>
     · 조회는 있었으나 자료원이 파일명을 주지 않은 근거. 본 보고서 사용 전 확인 필요

- 판정 기준은 하나다. `source_paths` 가 비어 있지 않으면 확인, 비어 있으면 미상.
  **검증상태(확인·부분확인·추정)를 보지 않는다.** 그것은 판단이고 이것은 사실이다.
- MRI 원문에 근거한 항목은 양쪽 어디에도 넣지 않고 따로 적는다 — `- MRI 원문 기반 <n>건`
- 출처 미상이 0건이면 그 줄을 뺀다. **0건이 아니면 절대 빼지 않는다.**"""

NEW_TPL = """    ○ (출처 확인 상태) 근거 <N>건
    - 출처 파일명 확인 <n>건 — <근거 번호 나열>
    - 출처 미상 <n>건 — <근거 번호 나열>
     · 조회는 있었으나 자료원이 파일명을 주지 않은 근거. 본 보고서 사용 전 확인 필요
    - MRI 원문 기반 <n>건 — <근거 번호 나열>

**N 은 근거 목록의 전체 건수다.** 어느 줄로 분류됐다고 총계에서 빼지 않는다.
「따로 적는다」는 **줄을 나눈다는 뜻이지 총계에서 뺀다는 뜻이 아니다.**

근거를 하나씩 보며 **세 줄 중 정확히 한 줄**에 넣는다. 순서대로 본다.

    1. `source_names` 에 「MRI 원문」이 있다        → MRI 원문 기반
    2. 그 밖에 `source_paths` 가 비어 있지 않다    → 출처 파일명 확인
    3. 그 밖에                                     → 출처 미상

- **이 두 칸만 본다.** 검증상태(확인·부분확인·추정)를 보지 않는다.
  그것은 판단이고 이것은 사실이다.
- **파일명이 없는 것과 MRI 에서 온 것은 다른 일이다.**
  자료원이 정책·뉴스·제로인·협회통계인 근거는 파일명이 없어도 「출처 미상」이지
  「MRI 원문 기반」이 아니다. 직전 실행에서 정책 5 · 뉴스 5 · 협회통계 3 으로
  조회된 근거 13건이 전부 「MRI 원문 기반」으로 실렸고, 그 탓에 총계가 0건이 됐다.
- **내기 전에 합을 맞춘다.** 세 줄의 합이 N 과 다르면 다시 센다. 예외가 없다.
- **N 은 뒤쪽 〈검수용〉의 「사용한 근거」 건수와 반드시 같다.** 같은 목록을 세는 것이기 때문이다.
  두 값이 다르면 이 블록이 틀린 것이다. 내기 전에 맞춘다.
  **이 블록이 본문보다 앞에 있으므로, 틀리면 읽는 사람이 본문 전체를 의심하게 된다.**
- 0건인 줄은 뺀다. **0건이 아닌 줄은 절대 빼지 않는다.**"""

OLD_AREA = """5개 영역에 근거가 붙었는지를 센다. 세 값만 쓴다 — `확보` · `부분` · `미확보`."""

NEW_AREA = """5개 영역에 근거가 붙었는지를 센다. 세 값만 쓴다 — `확보` · `부분` · `미확보`.

**근거 목록 전체를 본다.** 위에서 「MRI 원문 기반」으로 분류한 근거도 여기서는 같이 센다.
위의 세 줄은 출처를 나누는 칸이지 근거를 빼는 칸이 아니다."""

OLD_SCR = """인계 자료에 관점별 점수가 있을 때만 만든다."""

NEW_SCR = """인계 자료에 관점별 점수가 있을 때만 만든다.
오른쪽 칸은 **근거 목록 전체**에서 찾는다. 「MRI 원문 기반」 근거도 번호를 적는다."""


def patch(path):
    d = json.load(open(path, encoding='utf-8'))
    hit = 0
    for x in d['MapValue']['FunctionMaps']:
        p = x.get('prompt') or ''
        if '조사 결과 점검' not in p or 'N 은 근거 목록의 전체 건수다' in p:
            continue
        assert OLD_TPL in p and OLD_AREA in p and OLD_SCR in p, x.get('COL_NAME')
        p = p.replace(OLD_TPL, NEW_TPL, 1)
        p = p.replace(OLD_AREA, NEW_AREA, 1)
        p = p.replace(OLD_SCR, NEW_SCR, 1)
        x['prompt'] = p
        hit += 1
    json.dump(d, open(path, 'w', encoding='utf-8'), ensure_ascii=False, indent=2)
    print(f"{os.path.basename(path):<30} 점검 블록 {hit}곳")


if __name__ == '__main__':
    for f in (sys.argv[1:] or [os.path.join(HERE, t) for t in TARGETS]):
        if os.path.exists(f):
            patch(f)
